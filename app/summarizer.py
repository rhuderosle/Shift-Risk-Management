def render_text(shift: str, agg: dict[str, Any], bullets: list[str],
                period_start: datetime, period_end: datetime) -> str:
    lines = [
        f"SHIFT {shift} RISK PASSDOWN",
        f"{period_start:%Y-%m-%d %H:%M} -> {period_end:%Y-%m-%d %H:%M} UTC",
        "",
        f"Health index: {agg['health']}/100 | Open risks: {agg['open']} | Avg score: {agg['avg_score']}",
        f"Bands: " + ", ".join(f"{b}={agg['by_band'].get(b, 0)}" for b in BAND_COLORS),
        "",
        "EXECUTIVE SUMMARY",
    ]
    lines += [f"  - {b}" for b in bullets]
    lines += ["", "SHIFT REVIEW FOCUS"]
    lines += [f"  - {b}" for b in focus_bullets()]
    lines += ["", "TOP RISKS"]
    for r in agg["top"]:
        lines.append(
            f"  [{r['band']}] {r['title']} ({r['area']}, {r['owner'] or 'unassigned'}) "
            f"score={r['score']} action={r['action'] or 'TBD'}"
        )
        if (r.get("source_link") or "").strip():
            lines.append(f"      source: {r['source_link']}")
    if not agg["top"]:
        lines.append("  none")
    return "\n".join(lines)
