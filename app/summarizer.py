"""AI agent that turns aggregated shift risk data into an executive passdown summary.

Default is a deterministic rule-based narrative generator (no external calls).
If LLM_PROVIDER is set to `openai` or `azure` and credentials are present, the
narrative section is generated by the model, with automatic fallback to rules.
"""

from __future__ import annotations

import html
import logging
import re
from datetime import datetime
from typing import Any

import httpx

from .config import settings

log = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You are a manufacturing shift risk analyst. Given structured shift risk data, "
    "write a concise executive passdown: 3-6 bullet points covering the highest "
    "risks, their business impact, what the next shift must action first, and any "
    "escalation needed. Be specific, use the numbers provided, no preamble, no "
    "markdown headers. Plain bullet lines starting with '- '."
)


def _rule_narrative(shift: str, agg: dict[str, Any]) -> list[str]:
    bullets: list[str] = []
    crit = agg["by_band"].get("Critical", 0)
    high = agg["by_band"].get("High", 0)

    if agg["total"] == 0:
        return [f"No risks recorded for Shift {shift}. Clean handover — no open actions."]

    posture = (
        "ESCALATION REQUIRED" if crit else
        "ELEVATED" if high else
        "STABLE"
    )
    bullets.append(
        f"Shift {shift} risk posture is {posture}: {agg['open']} open risks "
        f"({crit} critical, {high} high), average risk score {agg['avg_score']}/100, "
        f"shift health index {agg['health']}/100."
    )

    for r in agg["critical"][:3]:
        bullets.append(
            f"CRITICAL — {r['title']} ({r['area']}, owner {r['owner'] or 'unassigned'}): "
            f"score {r['score']}, severity {r['severity']}/5, likelihood {r['likelihood']}/5, "
            f"{r['downtime_minutes']:.0f} min downtime exposure. "
            f"Next action: {r['action'] or 'assign owner and define containment'}."
        )

    if not agg["critical"]:
        for r in agg["top"][:2]:
            bullets.append(
                f"{r['band'].upper()} — {r['title']} ({r['area']}): score {r['score']}, "
                f"owner {r['owner'] or 'unassigned'}. "
                f"Next action: {r['action'] or 'review and confirm mitigation'}."
            )

    if agg["by_area"]:
        top_area, count = next(iter(agg["by_area"].items()))
        bullets.append(
            f"Risk concentration in {top_area} ({count} of {agg['total']} items) — "
            f"prioritise walkthrough of this area at handover."
        )

    bullets.append(
        f"Cumulative exposure this window: {agg['total_downtime_minutes']:.0f} downtime minutes "
        f"and {agg['total_impact_units']:.0f} impacted units."
    )

    unassigned = [r for r in agg["top"] if not r["owner"]]
    if unassigned:
        bullets.append(
            f"{len(unassigned)} of the top risks have no owner — assign before shift close."
        )
    return bullets


def _llm_narrative(shift: str, agg: dict[str, Any]) -> list[str] | None:
    provider = (settings.llm_provider or "none").lower()
    if provider not in ("openai", "azure"):
        return None
    payload_lines = [
        f"Shift: {shift}",
        f"Open risks: {agg['open']} / total {agg['total']}",
        f"Band counts: {agg['by_band']}",
        f"Average score: {agg['avg_score']}, health index: {agg['health']}",
        f"Downtime minutes: {agg['total_downtime_minutes']}, impacted units: {agg['total_impact_units']}",
        "Top risks:",
    ]
    for r in agg["top"]:
        payload_lines.append(
            f"- {r['title']} | area={r['area']} | owner={r['owner'] or 'unassigned'} | "
            f"band={r['band']} score={r['score']} sev={r['severity']} lik={r['likelihood']} | "
            f"action={r['action'] or 'none'} | notes={r['description'][:200]}"
        )
    user_prompt = "\n".join(payload_lines)

    try:
        if provider == "azure":
            if not (settings.azure_openai_endpoint and settings.azure_openai_deployment
                    and settings.openai_api_key):
                return None
            url = (
                f"{settings.azure_openai_endpoint.rstrip('/')}/openai/deployments/"
                f"{settings.azure_openai_deployment}/chat/completions"
                f"?api-version={settings.azure_openai_api_version}"
            )
            headers = {"api-key": settings.openai_api_key}
            body = {"messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ], "temperature": 0.2}
        else:
            if not settings.openai_api_key:
                return None
            url = f"{settings.openai_base_url.rstrip('/')}/chat/completions"
            headers = {"Authorization": f"Bearer {settings.openai_api_key}"}
            body = {"model": settings.openai_model, "temperature": 0.2, "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": user_prompt},
            ]}

        resp = httpx.post(url, json=body, headers=headers, timeout=45)
        resp.raise_for_status()
        content = resp.json()["choices"][0]["message"]["content"]
        bullets = [ln.lstrip("-• ").strip() for ln in content.splitlines() if ln.strip()]
        return bullets or None
    except Exception as exc:  # noqa: BLE001 - degrade gracefully to rules
        log.warning("LLM summarization failed, falling back to rules: %s", exc)
        return None


